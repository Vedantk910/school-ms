"""Generate docs/ml-eval.md: the deterministic ML evaluation report.

Seeds the full dataset, trains both tasks, and writes a markdown report with
the train/eval metric tables (GBR vs logistic vs majority baseline).
Run:  python -m tools.make_ml_eval
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
os.environ.setdefault("SCHOOLMS_DATABASE_URL", "sqlite:///:memory:")

REPO_DOCS = BACKEND.parent / "docs"


def main() -> None:
    from sqlmodel import Session
    from app.db import engine
    from seeds.generate import build
    from app.ml.train import train_task

    counts = build()  # full 550-student dataset
    print(f"seeded: {counts['students']} students, "
          f"{counts['attendance']} attendance rows in {counts['seconds']}s")

    with Session(engine) as session:
        reports = [train_task(session, "at_risk"), train_task(session, "fee_default")]

    out = [
        "# ML Evaluation Report (deterministic)",
        "",
        f"Generated by `tools/make_ml_eval.py` on seed `{counts['seed'] if 'seed' in counts else 42}`.",
        f"Dataset: {counts['students']} students, {counts['attendance']} attendance rows, "
        f"{counts['marks']} marks, {counts['bills']} bills across 5 academic years.",
        "Temporal split: train 2021-22..2024-25, evaluate 2025-26 (no shuffling across years).",
        "Model: HistGradientBoostingClassifier (sklearn), baselines: LogisticRegression + majority.",
        "",
    ]
    for rep in reports:
        g, lr, maj = rep["gbr"], rep["logreg"], rep["majority"]
        out += [
            f"## Task: {rep['task']}",
            "",
            f"- eval rows: {g['n_eval']}, base rate: {g['base_rate']:.1%}",
            "",
            "| model | AUC | AP | F1 | confusion [tn,fp,fn,tp] |",
            "|---|---|---|---|---|",
            f"| GBR | {g['auc']:.4f} | {g['ap']:.4f} | {g['f1']:.4f} | {g['confusion']} |",
            f"| logistic | {lr['auc']:.4f} | {lr['ap']:.4f} | {lr['f1']:.4f} | {lr['confusion']} |",
            f"| majority | {maj['auc']:.4f} | {maj['ap']:.4f} | {maj['f1']:.4f} | {maj['confusion']} |",
            "",
            f"- insights stored with SHAP top-5 reasons: {rep.get('insights_stored', 0)}",
            "",
        ]
    out += [
        "## Caveats",
        "",
        "- The dataset is **synthetic with strong archetype signal**, so near-perfect AUC is",
        "  expected and not a claim about real-world performance. The value here is the",
        "  **pipeline**: temporal split, no-leakage feature engineering, baselines, SHAP",
        "  explainability, and a reproducible evaluation — the parts that transfer to real data.",
        "- On real school data expect AUC 0.7-0.9 with noisier feature importances;",
        "  the SHAP top-k reasons remain the primary deliverable for counsellors.",
        "",
    ]
    REPO_DOCS.mkdir(exist_ok=True)
    (REPO_DOCS / "ml-eval.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", REPO_DOCS / "ml-eval.md")
    for rep in reports:
        print(f"  {rep['task']}: GBR AUC={rep['gbr']['auc']:.4f} "
              f"AP={rep['gbr']['ap']:.4f} "
              f"(majority AUC={rep['majority']['auc']:.4f})")


if __name__ == "__main__":
    main()
